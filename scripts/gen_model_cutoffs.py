#!/usr/bin/env python3
"""Regenerate internal/modelknowledge/cutoffs_gen.go from a models.dev api.json snapshot.

Usage: scripts/gen_model_cutoffs.py [path/to/api.json]   (downloads https://models.dev/api.json when omitted)
A model id that two providers list with different cutoffs is dropped: the cutoff is unknown, not guessed.
"""
import datetime
import json
import pathlib
import subprocess
import sys
import urllib.request

source = sys.argv[1] if len(sys.argv) > 1 else None
raw = open(source, "rb").read() if source else urllib.request.urlopen("https://models.dev/api.json", timeout=60).read()
catalog = json.loads(raw)
seen: dict[str, set[str]] = {}
for provider in catalog.values():
    for model_id, model in provider.get("models", {}).items():
        knowledge = model.get("knowledge")
        if knowledge:
            seen.setdefault(model_id.lower(), set()).add(knowledge)
entries = sorted((key, next(iter(values))) for key, values in seen.items() if len(values) == 1)
out = pathlib.Path(__file__).resolve().parent.parent / "internal/modelknowledge/cutoffs_gen.go"
lines = [
    "// Code generated by scripts/gen_model_cutoffs.py from https://models.dev (MIT); DO NOT EDIT.",
    "",
    "package modelknowledge",
    "",
    f'// snapshotDate is the day the models.dev snapshot was taken.',
    f'const snapshotDate = "{datetime.date.today().isoformat()}"',
    "",
    "// snapshot maps a lowercase model id to its knowledge cutoff (YYYY-MM or YYYY-MM-DD).",
    "var snapshot = map[string]string{",
]
lines += [f'\t"{key}": "{value}",' for key, value in entries]
lines += ["}", ""]
out.write_text("\n".join(lines))
subprocess.run(["gofmt", "-w", str(out)], check=True)
print(f"{len(entries)} models written to {out}")
